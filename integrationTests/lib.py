def run_tests(names):
    arguments = []      # Arguments for __run_single_test_module(list<str>, TestcaseFile)
    for name in sorted(names):
        name = name.split(".")
        if name[0] not in to_run:
            available = ", ".join(sorted(to_run.keys()))
            raise SystemExit(
                f"Unknown test module '{name[0]}'. Available modules: {available}"
            )
        case = to_run[name[0]]
        if len(name) > 1 and name[1].lower() not in [
            n.lower() for n in case.testcases_names]:
            available = ", ".join(case.testcases_names)
            raise SystemExit(
                f"Unknown testcase '{name[1]}' in module '{name[0]}'. "
                f"Available testcases: {available}"
            )
        arguments.append((name, case))

    # NOTE: modules run in parallel, testcases with in a module run sequentially
    # on one worker so they can share the compiled binary and directories.

    if len(arguments) == 1:
        results = [__run_single_test_module(*arguments[0])]
    else:
        # Each test module is loaded by tests/__init__.py under a bare name
        # (e.g. "extra_credit") that only exists in sys.modules, not as a
        # real importable package. A worker needs that already done before
        # it can unpickle tasks referencing those modules' functions, which
        # only "spawn" (the macOS/Windows default) leaves out, since it
        # starts from a blank interpreter instead of copying the parent's
        # already-populated sys.modules. Forcing "fork" keeps the loaded
        # modules.
        with multiprocessing.get_context("fork").Pool(min(cpu_count(), len(arguments))) as p:
            results = p.starmap(__run_single_test_module, arguments)

    if False in results: 
        with bold + red:
            print(f"{results.count(True)}/{len(results)} modules passed")
        sys.exit(1)
    else:
        with bold + green:
            print(f"All {len(results)} modules passed")


def run_all():
    run_tests(to_run.keys())


def __run_single_test_module(name, case):
    key = name[0]
    with bold:
        print(f"---- BEGIN TEST MODULE {key.upper()} ----")

    module_success = __compile_test_module(case)
    if module_success:
        testcases = __collect_test_cases(case, name)
        succeed_count = len(testcases)
        for index, f in zip(range(1, len(testcases) + 1), testcases):
            if not __execute_test_case(index, f):
                succeed_count -= 1
        if succeed_count == len(testcases):
            with bold + green: 
                print("All testcases passed")
        else:
            with bold + red:
                print(f"{succeed_count}/{len(testcases)} testcases passed")
            module_success = False

    if not module_success and isinstance(case.wrapper, TestcaseWrapper):
        with yellow:
            print(f"Scratch directory kept at {case.wrapper.data_path}")

    with bold:
        print(f"---- END TEST MODULE {key.upper()} ----")
    print()
    return module_success

def __compile_test_module(case):
    try:
        print("Starting compilation...")
        case.prebuild()
        case.wrapper.build()
        print("Finished comilation...")
        return True
    except Exception as e:
        print(f"Build failed with exception: {e}")
        return False


def __collect_test_cases(case, name):
    if len(name) > 1:
        return [
            case.testcases_names[i]
            for i in range(len(case.testcases))
            if str(case.testcase_names[i]).lower() == name[1].lower()
        ]
    return case.testcases


def __execute_test_case(index, test_case):
    try:
        test_case()
        return True
    except Exception as e:
        with bold + red:
            lineno = None
            tb = traceback.extract_tb(sys.exc_info()[2])
            for i in range(len(tb) - 1, -1, -1):
                if os.path.basename(tb[i][0]) == "__init__.py":
                    lineno = tb[i][1]
            print(f"Testcase {index} failed on line {lineno} with exception: {e}")
        return False


