from collections import defaultdict
from functools import wraps
import multiprocessing
from multiprocessing import cpu_count
import difflib
import inspect
import os
import re
import shutil
import subprocess
import sys
import traceback


INTEGRATION_TEST_ROOT = os.path.dirname(os.path.realpath(__file__))
RAINBOW_GRADES_DIR = os.path.dirname(INTEGRATION_TEST_ROOT)

# Set by run.py when invoked with --update
UPDATE_VALIDATION = False

###################################################################################
# Test registry
#
# Concurrency note (same constraint as Submitty's framework): to survive being
# passed across a process boundary there must be no lambdas in TestcaseFile and
# every wrapper must be annotated with functools.wraps, so that Python can
# pickle them for the worker process.
###################################################################################

class TestcaseFile:
    def __init__(self):
        self.wrapper = type(None)
        self.prebuild = type(None)
        self.testcases = []
        self.testcases_names = []


to_run = defaultdict(lambda: TestcaseFile(), {})


